"""A mock, in-process RAG adapter for testing purposes."""

from typing import List

from eval.adapters.base import BaseRAGAdapter
from eval.schemas.data_models import (
    Context,
    Query,
    RAGOutput,
    RAGTrace,
    TokenUsage,
    Turn,
)


class MockRAGAdapter(BaseRAGAdapter):
    """
    A mock RAG adapter that returns fixed, dummy data.

    This adapter is useful for testing the evaluation runner's pipeline
    without making actual calls to a RAG system.
    """

    def get_response(self, query: Query) -> RAGOutput:
        """
        Returns a canned response for any given query.

        Args:
            query: The input query object (ignored in this mock implementation).

        Returns:
            A fixed RAGOutput object with dummy data.
        """
        # Simulate a RAG system's response with mock data
        mock_contexts = [
            Context(
                doc_id="mock-doc-1",
                score=0.95,
                text="This is the content of the first mock document.",
                metadata={"source": "mock_source_1.txt"},
            ),
            Context(
                doc_id="mock-doc-2",
                score=0.88,
                text="This is the content of the second mock document.",
                metadata={"source": "mock_source_2.pdf"},
            ),
        ]

        mock_answer = (
            "Based on the retrieved context, the answer is generated by the mock adapter."
        )

        # Simulate trace information
        mock_trace = RAGTrace(
            prompt="This is a mock prompt sent to the LLM.",
            token_usage=TokenUsage(input=123, output=456),
        )

        return RAGOutput(
            answer=mock_answer,
            contexts=mock_contexts,
            citations=["mock-doc-1"],
            trace=mock_trace,
        )

    def get_conversation_response(self, turns: List[Turn]) -> RAGOutput:
        """
        Returns a canned response for the last turn in a conversation.

        This mock implementation generates a response based on the last user
        message, ignoring the conversation history for simplicity.

        Args:
            turns: The full list of turns in the conversation.

        Returns:
            A fixed RAGOutput object with dummy data.
        """
        last_user_turn = next((turn for turn in reversed(turns) if turn.role == "user"), None)
        question = last_user_turn.content if last_user_turn else "No user input found."

        mock_contexts = [
            Context(
                doc_id="conv-mock-doc-1",
                score=0.92,
                text=f"This is mock context related to: '{question}'",
                metadata={"source": "conversation_source.txt"},
            ),
        ]

        mock_answer = f"This is a mock conversational answer to the question: '{question}'"

        mock_trace = RAGTrace(
            prompt=f"Mock prompt for conversation turn: {question}",
            token_usage=TokenUsage(input=250, output=150),
        )

        return RAGOutput(
            answer=mock_answer,
            contexts=mock_contexts,
            citations=["conv-mock-doc-1"],
            trace=mock_trace,
        )
